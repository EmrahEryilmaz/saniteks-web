/**
 * Collects every translatable Turkish string and checks the translation files.
 *
 *   npm run i18n:extract   writes scripts/i18n/strings.json (source strings + where they come from) and
 *                          src/i18n/client-keys.ts (strings used in "use client" files)
 *   npm run i18n:check     also fails when a language misses a translation or has a broken placeholder
 *
 * Sources: t("…") calls in src/ (the translate function must be named `t`) and the data registered in
 * src/i18n/sources.ts (walked like translate.ts › localizeDeep, so the same keys are skipped).
 */
import { readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { translatableData } from "../../src/i18n/sources.ts";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const src = path.join(root, "src");
const check = process.argv.includes("--check");

type Entry = { files: Set<string>; client: boolean };
const strings = new Map<string, Entry>();
const add = (text: string, where: string, client = false) => {
  if (!text.trim()) return;
  const e = strings.get(text) ?? { files: new Set<string>(), client: false };
  e.files.add(where);
  e.client ||= client;
  strings.set(text, e);
};

function walk(dir: string): string[] {
  return readdirSync(dir).flatMap((name) => {
    const full = path.join(dir, name);
    return statSync(full).isDirectory() ? walk(full) : /\.(ts|tsx)$/.test(name) ? [full] : [];
  });
}

const unescape = (s: string, quote: string) =>
  s.replace(/\\(u\{[0-9a-fA-F]+\}|u[0-9a-fA-F]{4}|n|t|\\|"|'|`)/g, (m, x: string) => {
    if (x.startsWith("u{")) return String.fromCodePoint(parseInt(x.slice(2, -1), 16));
    if (x.startsWith("u")) return String.fromCharCode(parseInt(x.slice(1), 16));
    return x === "n" ? "\n" : x === "t" ? "\t" : x === quote || x === "\\" || x === "'" || x === '"' || x === "`" ? x : m;
  });

const callRe = /(?<![\w$.])t\(\s*(["'`])((?:\\.|(?!\1)[^\\])*?)\1/gs;
for (const file of walk(src)) {
  if (file.includes(`${path.sep}i18n${path.sep}translations`)) continue;
  const code = readFileSync(file, "utf8");
  const client = /^\s*["']use client["']/.test(code);
  const rel = path.relative(root, file);
  for (const m of code.matchAll(callRe)) {
    if (m[1] === "`" && m[2].includes("${")) {
      console.warn(`! ${rel}: t(\`…\${…}\`) cannot be translated — use placeholders: ${m[2].slice(0, 60)}`);
      continue;
    }
    add(unescape(m[2], m[1]), rel, client);
  }
}

const skipKeys = new Set([
  "slug", "id", "code", "categorySlug", "packaging", "image", "src", "href", "url", "file", "logo", "hex", "nameEn",
  "number", "validFrom", "validUntil", "email", "phone", "phoneHref", "phoneE164", "mapsHref", "path", "icon",
  "position", "kind", "variant", "key",
]);
function collect(value: unknown, where: string, key?: string) {
  if (typeof value === "string") {
    if (!(key && skipKeys.has(key))) add(value, where);
  } else if (Array.isArray(value)) value.forEach((v) => collect(v, where, key));
  else if (value && typeof value === "object") for (const [k, v] of Object.entries(value)) collect(v, where, k);
}
for (const [name, value] of Object.entries(translatableData)) collect(value, `data:${name}`);

const sorted = [...strings.entries()].sort(([a], [b]) => a.localeCompare(b, "tr"));
writeFileSync(
  path.join(root, "scripts/i18n/strings.json"),
  JSON.stringify(Object.fromEntries(sorted.map(([s, e]) => [s, [...e.files].sort()])), null, 2) + "\n",
);
const clientKeys = sorted.filter(([, e]) => e.client).map(([s]) => s);
writeFileSync(
  path.join(src, "i18n/client-keys.ts"),
  `// Generated by scripts/i18n/extract.ts — Turkish strings used inside "use client" components. Do not edit by hand.\nexport const clientKeys: string[] = ${JSON.stringify(clientKeys, null, 2)};\n`,
);
console.log(`${strings.size} strings (${clientKeys.length} in client components) → scripts/i18n/strings.json`);

const placeholders = (s: string) => [...s.matchAll(/\{(\w+)\}/g)].map((m) => m[1]).sort().join(",");
let problems = 0;
for (const locale of ["en", "de", "ar", "ru"]) {
  const dict = JSON.parse(readFileSync(path.join(src, `i18n/translations/${locale}.json`), "utf8")) as Record<string, string>;
  const missing = sorted.filter(([s]) => !dict[s]?.trim()).map(([s]) => s);
  const unused = Object.keys(dict).filter((k) => !strings.has(k));
  const broken = Object.entries(dict).filter(([k, v]) => strings.has(k) && placeholders(k) !== placeholders(v)).map(([k]) => k);
  console.log(`${locale}: ${missing.length} missing, ${unused.length} unused, ${broken.length} broken placeholders`);
  if (check) {
    for (const s of missing.slice(0, 20)) console.log(`  missing: ${s.slice(0, 100)}`);
    for (const s of broken) console.log(`  placeholder mismatch: ${s.slice(0, 100)}`);
    problems += missing.length + broken.length;
  }
}
if (check && problems) {
  console.error(`i18n check failed: ${problems} problem(s).`);
  process.exit(1);
}
