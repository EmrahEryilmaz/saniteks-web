// Runs after `next build`: the standalone server does not include `public/` and `.next/static/`,
// so copy them next to .next/standalone/server.js (https://nextjs.org/docs → output: "standalone").
import fs from "node:fs";
import path from "node:path";

const root = process.cwd();
const standalone = path.join(root, ".next", "standalone");

if (!fs.existsSync(path.join(standalone, "server.js"))) {
  console.error("prepare-standalone: .next/standalone/server.js bulunamadı — next.config.ts içinde output: \"standalone\" olmalı.");
  process.exit(1);
}

for (const [from, to] of [
  [path.join(root, "public"), path.join(standalone, "public")],
  [path.join(root, ".next", "static"), path.join(standalone, ".next", "static")],
]) {
  fs.rmSync(to, { recursive: true, force: true });
  fs.cpSync(from, to, { recursive: true });
  console.log(`prepare-standalone: ${path.relative(root, from)} → ${path.relative(root, to)}`);
}

// Plesk's Passenger does not reliably honour tmp/restart.txt, so a deploy (Plesk Git checkout) can leave the old
// process serving the previous build. The startup file stays `server.js`, but it becomes a small wrapper: it starts
// Next's server (renamed next-server.js) and exits as soon as the REVISION file written by the deploy workflow
// changes; Passenger then starts the new build on the next request.
const nextServer = path.join(standalone, "next-server.js");
fs.renameSync(path.join(standalone, "server.js"), nextServer);
fs.writeFileSync(
  path.join(standalone, "server.js"),
  `// Generated by scripts/prepare-standalone.mjs — see the comment there.
const fs = require("node:fs");
const path = require("node:path");

const revisionFile = path.join(__dirname, "REVISION");
const read = () => {
  try {
    return fs.readFileSync(revisionFile, "utf8").trim();
  } catch {
    return null;
  }
};
const started = read();

if (started !== null) {
  setInterval(() => {
    const now = read();
    if (now !== null && now !== started) {
      console.log(\`saniteks: yeni sürüm (\${now}); yeniden başlatmak için süreç kapanıyor.\`);
      process.exit(0);
    }
  }, 5000).unref();
}

require("./next-server.js");
`,
);
console.log("prepare-standalone: server.js → next-server.js (+ sürüm izleyen başlatıcı)");
